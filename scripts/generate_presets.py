"""Generate runnable preset wrappers from a shared, validated configuration catalog."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "Script Presets" / "presets.json"


def potassium_options(preset: dict) -> dict:
    options = dict(preset["options"])
    options["IgnoreSpecialProperties"] = False
    options["AlternativeWritefile"] = preset["id"] != "DiagnosticSavePlace"
    return options


def lua(value: object, level: int = 0) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "{ " + ", ".join(lua(item, level + 1) for item in value) + " }" if value else "{}"
    if isinstance(value, dict):
        lines = ["{"]
        for key, item in value.items():
            if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", key):
                raise ValueError(f"Invalid Luau option name: {key}")
            lines.append("\t" * (level + 1) + key + " = " + lua(item, level + 1) + ",")
        return "\n".join(lines + ["\t" * level + "}"])
    raise ValueError(f"Unsupported preset value: {value!r}")


def render() -> dict[Path, str]:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    if catalog["schemaVersion"] != 1:
        raise ValueError("Unsupported preset catalog schema")
    template = Template((ROOT / "scripts/templates/preset.luau").read_text(encoding="utf-8"))
    source = (ROOT / "saveinstance.luau").read_text(encoding="utf-8")
    documented = set(re.findall(r"^--- (?:@field |\.)(\w+) ", source, re.MULTILINE))
    identifiers: set[str] = set()
    outputs: dict[Path, str] = {}
    version = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))["version"]
    for preset in catalog["presets"]:
        identifier = preset["id"]
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", identifier) or identifier in identifiers:
            raise ValueError(f"Invalid or duplicate preset identifier: {identifier}")
        identifiers.add(identifier)
        options = preset["options"]
        unknown = set(options) - documented
        if unknown:
            raise ValueError(f"{identifier}: undocumented options: {sorted(unknown)}")
        if options.get("Binary") is not True:
            raise ValueError(f"{identifier}: this wrapper currently requires binary place output")
        for key in ("SafeMode", "KillAllScripts", "BoostFPS", "ShutdownWhenDone"):
            if options.get(key) is not False:
                raise ValueError(f"{identifier}: {key} must be explicitly disabled in this catalog")
        for enabled, timeout in (("Decompile", "DecompileTimeout"), ("SaveBytecode", "BytecodeTimeout")):
            if options.get(enabled):
                value = options.get(timeout)
                if isinstance(value, bool) or not isinstance(value, (int, float)) or value <= 0:
                    raise ValueError(f"{identifier}: {timeout} must be a positive per-job timeout")
        outputs[ROOT / "Script Presets" / f"{identifier}.luau"] = template.substitute(
            PRESET_ID=identifier, SUMMARY=preset["summary"], STATUS=preset["status"], OPTIONS=lua(options),
            VERSION=version, CORE_PATH="CompleteSavePlace/saveinstance.luau",
            CORE_URL_PATH="saveinstance.luau", PROFILE="Universal",
            GPS_ENABLED=lua(preset.get("gps", False)),
        )
        outputs[ROOT / "Executors/Potassium/Script Presets" / f"{identifier}.luau"] = template.substitute(
            PRESET_ID=identifier, SUMMARY=preset["summary"] + " Potassium profile.", STATUS=preset["status"],
            OPTIONS=lua(potassium_options(preset)), VERSION=version,
            CORE_PATH="CompleteSavePlace/Executors/Potassium/saveinstance.luau",
            CORE_URL_PATH="Executors/Potassium/saveinstance.luau", PROFILE="Potassium",
            GPS_ENABLED=lua(preset.get("gps", False)),
        )
    if catalog["developmentTarget"] not in identifiers:
        raise ValueError("Development target is missing from the catalog")

    lines = [
        "# Script Presets", "", "<!-- Generated by scripts/generate_presets.py. -->", "",
        "Runnable configurations for the shared CompleteSavePlace engine.", "",
        f"**Current development target: {catalog['developmentTarget']}.**", "",
        "All presets remain unverified in Roblox. Ultra is experimental and targets the widest accessible coverage.", "",
    ]
    for preset in catalog["presets"]:
        identifier = preset["id"]
        lines += [f"## [{identifier}]({identifier}.luau)", "", preset["summary"], "", *( ["GPS collection settings and limits: [guide](../docs/PRESETS.md#gps-streaming-collection).", ""] if preset.get("gps") else [] ),
                  f"Status: `{preset['status']}`.", "", "Run this preset:", "", "```lua",
                  "loadstring(game:HttpGet(",
                  f'    "https://raw.githubusercontent.com/g0shtj0sh/CompleteSavePlace/v{version}/Script%20Presets/{identifier}.luau",',
                  "    true", "))()", "```", "", "Options:", "", "```lua", lua(preset["options"]), "```", ""]
    lines += [
        "## Export files", "",
        "Each run creates `Game title - Preset/Game title.rbxl`, with `progress.json` and `report.json` in that folder.",
        "Existing folders get numbered suffixes, such as ` (2)`, on the folder only. Unicode titles are preserved; invalid path characters are replaced.",
        "The runtime needs `makefolder` and `isfolder`. A temporary `write-test.tmp` probes writing and is removed when `delfile` is available.", "",
        "## Running a preset", "",
        "Use a versioned loader above, or copy the engine and preset into your runtime's file workspace:", "",
        "```text", "CompleteSavePlace/", "  saveinstance.luau", "  Script Presets/",
        "    UltraCompleteSavePlace.luau", "```", "",
        "Execute the chosen preset through the runtime's local script facility, or use the versioned loader above.", "",
        f"The preset downloads the engine pinned to `v{version}` by default, avoiding stale local copies.",
        "For local development, explicitly set `USE_LOCAL_CORE = true` and adjust `CORE_PATH`.",
        "No GitHub token is required. The runtime still needs HTTP access and file APIs.", "",
        "The wrapper performs a basic text write/read probe, creates a separate game-and-preset folder, and checks file existence when available.",
        "It never treats an existing file as proof of valid contents. Open the result in Studio.", "",
        "A `report.json` sidecar records the engine version, source, class counts, output existence, and omitted binary property columns.",
        "A `progress.json` checkpoint records the latest operation while running; preserve it if the client freezes before a final report exists.",
        "Per-job deadlines cannot interrupt native calls that block the entire client. See [troubleshooting](../docs/TROUBLESHOOTING.md).",
        "Geometry warnings identify omitted terrain or mesh data; they do not identify the missing road without further inspection.", "",
        "## Development", "",
        "Edit `presets.json`, then run `python scripts/generate_presets.py` from the repository root.",
        "The serializer is shared; engine fixes apply to every preset without copying the core.", "",
        "See [the preset guide](../docs/PRESETS.md) for differences, limits, and the Ultra development focus.", "",
        "Potassium users can use the [dedicated engine and presets](../Executors/Potassium/README.md).", "",
    ]
    outputs[ROOT / "Script Presets" / "README.md"] = "\n".join(lines)
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when generated files differ")
    args = parser.parse_args()
    outputs = render()
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Regenerate presets: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"Preset catalog {'checked' if args.check else 'generated'} ({len(outputs) - 1} executable presets, Universal + Potassium).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
